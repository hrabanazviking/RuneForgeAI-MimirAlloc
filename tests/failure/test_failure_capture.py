"""Tests for scripts/failure_capture.py (MimirAlloc TEAM-05, A-005).

Contract under test (Builder A harness):
  CLI:  failure_capture.py run --case X [--out-root DIR]
        failure_capture.py verify DIR
  Exit codes: 0 = matches expected, 2 = unexpected outcome,
              3 = harness error, 4 = timeout-killed.
  Packet: manifest.json, case.json, command.txt,
          stdout.log, stderr.log, SHA256SUMS.
  Manifest fields include: claim_scope (str), classification
  ("unclassified"), page_size_bytes, exit_code, matches_expected,
  first_relevant_error, timed_out.

Stdlib unittest only. Tests write only to tempfile dirs.
"""

import json
import os
import subprocess
import sys
import tempfile
import time
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HARNESS = ROOT / "scripts" / "failure_capture.py"
SMOKE_CASE = ROOT / "scripts" / "failure_cases" / "smoke_fail.json"
SMOKE_ERROR = "smoke: first relevant error: deliberate exit 3"


def base_case(**overrides):
    case = {
        "schema_version": 1,
        "id": "test-case",
        "title": "Synthetic test case",
        "stage": "other",
        "failing_process": "other",
        "argv": ["/bin/true"],
        "cwd": ".",
        "env_add": {},
        "timeout_seconds": 10,
        "expected": {"outcome": "pass", "exit_code": 0},
        "classification_hint": None,
        "notes": "Generated by test_failure_capture.py",
    }
    case.update(overrides)
    return case


class FailureCaptureTests(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory(prefix="failcap-test-")
        self.tmp = Path(self._tmp.name)
        self.out_root = self.tmp / "out"
        self.out_root.mkdir(parents=True, exist_ok=True)

    def tearDown(self):
        self._tmp.cleanup()

    # -- helpers -----------------------------------------------------

    def write_case(self, case, name="case.json"):
        path = self.tmp / name
        if isinstance(case, str):
            path.write_text(case, encoding="utf-8")
        else:
            path.write_text(json.dumps(case), encoding="utf-8")
        return path

    def run_harness(self, *args):
        return subprocess.run(
            [sys.executable, str(HARNESS), *args],
            cwd=str(ROOT),
            capture_output=True,
            text=True,
            timeout=60,
        )

    def run_case(self, case_path):
        return self.run_harness(
            "run", "--case", str(case_path),
            "--out-root", str(self.out_root),
        )

    def find_packet(self):
        """Locate the packet dir under out_root robustly.

        Accepts either out_root itself being the packet, or a
        (possibly nested) subdirectory containing manifest.json.
        Returns (packet_dir, manifest_dict).
        """
        candidates = []
        direct = self.out_root / "manifest.json"
        if direct.is_file():
            candidates.append(self.out_root)
        for manifest in self.out_root.rglob("manifest.json"):
            if manifest.parent not in candidates:
                candidates.append(manifest.parent)
        self.assertTrue(
            candidates,
            "no manifest.json packet found under %s" % self.out_root,
        )
        # Newest packet wins if several exist.
        packet = max(
            candidates,
            key=lambda p: (p / "manifest.json").stat().st_mtime,
        )
        manifest = json.loads(
            (packet / "manifest.json").read_text(encoding="utf-8"))
        return packet, manifest

    # -- (a) expected-fail smoke case --------------------------------

    def test_a_expected_fail_smoke_case(self):
        self.assertTrue(HARNESS.is_file(), "harness missing: %s" % HARNESS)
        self.assertTrue(SMOKE_CASE.is_file(), "smoke case missing")
        result = self.run_case(SMOKE_CASE)
        self.assertEqual(
            result.returncode, 0,
            "harness should exit 0 on matching expected failure; "
            "stdout=%r stderr=%r" % (result.stdout, result.stderr))
        packet, manifest = self.find_packet()
        for name in ("manifest.json", "case.json", "command.txt",
                     "stdout.log", "stderr.log", "SHA256SUMS"):
            self.assertTrue((packet / name).is_file(),
                            "packet missing %s" % name)
        self.assertEqual(manifest["exit_code"], 3)
        self.assertIs(manifest["matches_expected"], True)
        self.assertEqual(manifest["first_relevant_error"], SMOKE_ERROR)
        self.assertIsInstance(manifest["claim_scope"], str)
        self.assertTrue(manifest["claim_scope"])
        self.assertEqual(manifest["classification"], "unclassified")
        self.assertIn(SMOKE_ERROR,
                      (packet / "stderr.log").read_text(encoding="utf-8"))

    # -- (b) expected-pass /bin/true case ----------------------------

    def test_b_expected_pass_true_case(self):
        case = base_case(id="pass-true", argv=["/bin/true"],
                         expected={"outcome": "pass", "exit_code": 0})
        result = self.run_case(self.write_case(case))
        self.assertEqual(
            result.returncode, 0,
            "stdout=%r stderr=%r" % (result.stdout, result.stderr))
        _packet, manifest = self.find_packet()
        self.assertEqual(manifest["exit_code"], 0)
        self.assertIs(manifest["matches_expected"], True)

    # -- (c) timeout --------------------------------------------------

    def test_c_timeout_kills_and_leaves_no_orphan(self):
        case = base_case(
            id="timeout-sleep",
            argv=["/bin/sleep", "30"],
            timeout_seconds=1,
            expected={"outcome": "pass", "exit_code": 0},
        )
        started = time.time()
        result = self.run_case(self.write_case(case))
        elapsed = time.time() - started
        self.assertEqual(
            result.returncode, 4,
            "timeout should give harness exit 4; got %s "
            "stdout=%r stderr=%r" % (
                result.returncode, result.stdout, result.stderr))
        self.assertLess(elapsed, 20,
                        "harness did not kill the child promptly")
        _packet, manifest = self.find_packet()
        self.assertIs(manifest["timed_out"], True)
        self.assertIs(manifest["matches_expected"], False)
        # No orphan sleep process may survive the kill.
        time.sleep(0.5)
        orphans = []
        try:
            ps = subprocess.run(
                ["pgrep", "-af", "sleep 30"],
                capture_output=True, text=True, timeout=10)
            lines = [ln for ln in ps.stdout.splitlines() if ln.strip()]
            # Exclude any pgrep line referring to this test itself.
            orphans = [ln for ln in lines
                       if "test_failure_capture" not in ln]
        except (FileNotFoundError, subprocess.SubprocessError):
            proc = Path("/proc")
            for entry in proc.iterdir():
                if not entry.name.isdigit():
                    continue
                try:
                    cmdline = (entry / "cmdline").read_bytes()
                except OSError:
                    continue
                parts = cmdline.split(b"\x00")
                if parts[:2] == [b"/bin/sleep", b"30"]:
                    orphans.append(entry.name)
        self.assertEqual(orphans, [],
                         "orphan sleep processes remain: %r" % orphans)

    # -- (d) malformed case JSON --------------------------------------

    def test_d_malformed_case_json_is_harness_error(self):
        bad = self.write_case("{ this is not valid json ", "bad.json")
        result = self.run_case(bad)
        self.assertEqual(
            result.returncode, 3,
            "malformed case should give exit 3; got %s "
            "stdout=%r stderr=%r" % (
                result.returncode, result.stdout, result.stderr))

    # -- (e) SECRET-named env_add key rejected -------------------------

    def test_e_secret_env_key_rejected(self):
        case = base_case(
            id="secret-env",
            env_add={"API_SECRET_TOKEN": "must-never-be-accepted"},
        )
        result = self.run_case(self.write_case(case))
        self.assertEqual(
            result.returncode, 3,
            "SECRET-named env_add key should be rejected with "
            "exit 3; got %s stdout=%r stderr=%r" % (
                result.returncode, result.stdout, result.stderr))

    # -- (f) verify subcommand on a fresh packet -----------------------

    def test_f_verify_passes_on_fresh_packet(self):
        case = base_case(id="verify-true", argv=["/bin/true"],
                         expected={"outcome": "pass", "exit_code": 0})
        result = self.run_case(self.write_case(case))
        self.assertEqual(result.returncode, 0,
                         "setup run failed: %r %r" % (
                             result.stdout, result.stderr))
        packet, _manifest = self.find_packet()
        verify = self.run_harness("verify", str(packet))
        self.assertEqual(
            verify.returncode, 0,
            "verify should pass on a fresh packet; got %s "
            "stdout=%r stderr=%r" % (
                verify.returncode, verify.stdout, verify.stderr))

    # -- (g) page_size_bytes matches this host -------------------------

    def test_g_page_size_matches_host(self):
        result = self.run_case(SMOKE_CASE)
        self.assertEqual(result.returncode, 0,
                         "setup run failed: %r %r" % (
                             result.stdout, result.stderr))
        _packet, manifest = self.find_packet()
        expected_page = os.sysconf("SC_PAGE_SIZE")
        self.assertEqual(manifest["page_size_bytes"], expected_page)


if __name__ == "__main__":
    unittest.main()
